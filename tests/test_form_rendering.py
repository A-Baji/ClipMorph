"""Frontend form-rendering guards for issue #259 (D6, D7, D8, C4, C5).

The configuration form is generated by ``frontend/src/components/ConfigForm.svelte``
on top of two pure units, ``frontend/src/lib/form.js`` (control mapping) and
``frontend/src/components/PlatformSection.svelte`` (platform grouping). The
backend spec generator is already covered by ``tests/test_form_spec.py``; these
tests pin the frontend half of the same contract at the source level using the
repo's existing drift-guard pattern (see ``tests/test_platforms.py``).
"""

import re
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
FRONTEND_SRC = REPO_ROOT / "frontend" / "src"
FORM_JS = FRONTEND_SRC / "lib" / "form.js"
CONFIG_FORM = FRONTEND_SRC / "components" / "ConfigForm.svelte"
PLATFORM_SECTION = FRONTEND_SRC / "components" / "PlatformSection.svelte"
WIZARD_VIEW = FRONTEND_SRC / "views" / "WizardView.svelte"
JOBS_VIEW = FRONTEND_SRC / "views" / "JobsView.svelte"
THUMBNAIL = FRONTEND_SRC / "components" / "Thumbnail.svelte"
API_JS = FRONTEND_SRC / "lib" / "api.js"
ICON = FRONTEND_SRC / "components" / "Icon.svelte"


def source(path: Path) -> str:
    """A frontend source file must exist and be tracked content."""
    return path.read_text(encoding="utf-8")


class ControlMappingTests(unittest.TestCase):
    """D7: the control a field renders follows type metadata."""

    def test_free_text_is_exactly_title_description_tags(self):
        module = source(FORM_JS)
        entries = re.findall(r"FREE_TEXT_PATHS = new Set\(\[([^]]*)\]", module, re.DOTALL)[0]
        free_text = set(re.findall(r"'([^']+)'", entries))
        self.assertEqual(
            free_text,
            {
                "upload.content.title",
                "upload.content.description",
                "upload.content.tags",
            },
        )

    def test_inline_layout_object_field_never_renders(self):
        config_form = source(CONFIG_FORM)
        # D7: the spec's only object field ('Inline layout') never reaches a
        # widget — no object-input branch, and the removed object textarea.
        self.assertNotIn("field.type === 'object'", config_form)
        self.assertNotIn("onInput(path, 'object'", config_form)
        self.assertIn("kind: 'hidden'", source(FORM_JS))

    def test_enumerated_fields_map_to_selects(self):
        module = source(FORM_JS)
        # Spec-declared enums plus the D7 enumerated strings.
        for leaf in (
            "transcription_model",
            "transcription_device",
            "transcription_compute_type",
            "privacy_status",
            "privacy_level",
            "content_kind",
            "category",
        ):
            self.assertIn(leaf, module)
        # The layout-preset dropdown is resolved from /api/v1/layouts data.
        self.assertIn("'conversion.layout_id'", module)
        self.assertIn("layouts", module)

    def test_datetime_fields_render_as_datetime_inputs(self):
        self.assertIn("kind: 'datetime'", source(FORM_JS))
        self.assertIn("type=\"datetime-local\"", source(CONFIG_FORM))

    def test_option_labels_are_humanized_never_raw_keys(self):
        module = source(FORM_JS)
        self.assertIn("enumLabel", module)
        self.assertIn("MUTUAL_FOLLOW_FRIENDS", module)
        self.assertIn("label: 'Mutual follow friends'", module)


class RowAssociationTests(unittest.TestCase):
    """D6: every form row is one association, not detached control columns."""

    def test_checkbox_sits_inside_a_wrapping_label(self):
        # The checkbox branch renders input immediately left of its visible
        # label text inside one wrapping <label for>-associated element.
        config_form = source(CONFIG_FORM)
        checkbox_index = config_form.index('kind === \'checkbox\'')
        block = config_form[checkbox_index:checkbox_index + 1200]
        self.assertIn("<label", block)
        self.assertIn("type=\"checkbox\"", block)
        self.assertIn("<span>{field.label}</span>", block)
        # The visible label text, not an aria-label, carries the name.
        self.assertNotIn("aria-label={field.label}", block)

    def test_text_number_and_select_controls_associate_via_for(self):
        config_form = source(CONFIG_FORM)
        # The stacked branches bind their label with for={fid} and set id={fid}
        # on the control; no aria-label fallback remains.
        self.assertNotIn('aria-label={field.label}', config_form)
        self.assertIn("for={fid}", config_form)
        self.assertIn("id={fid}", config_form)

    def test_single_control_column(self):
        config_form = source(CONFIG_FORM)
        self.assertNotIn("grid-template-columns: auto", config_form)


class PlatformGroupingTests(unittest.TestCase):
    """D8: one "Platform" node, one node per platform, enable toggle at level."""

    def test_wizard_renders_the_grouping_component_for_batch_and_job(self):
        wizard = source(WIZARD_VIEW)
        self.assertIn("<PlatformSection", wizard)
        self.assertEqual(wizard.count("pane-platforms"), 0)

    def test_platform_node_collapsed_by_default_with_level_toggle(self):
        section = source(PLATFORM_SECTION)
        # A single collapsible container labelled Platform.
        self.assertIn('platform-group', section)
        self.assertIn(">Platform</span>", section)
        # No `open` attribute: the group and its per-platform nodes start
        # collapsed (D8), unlike the batch pane's own sections (D9).
        self.assertNotIn(" open", section.split(".platform-nodes")[0])
        # The enable toggle rides the platform node summary, inverted against
        # the underlying per-platform upload.skip flag.
        self.assertIn("upload.skip", section)
        self.assertIn("return !skip;", section)
        self.assertIn("checked={enabled(platform)}", section)

    def test_platform_sections_and_flat_options_merge_into_one_form(self):
        section = source(PLATFORM_SECTION)
        self.assertIsInstance(section.count("<ConfigForm"), int)
        self.assertLessEqual(section.count("<ConfigForm"), 1)
        self.assertIn("flat_fields", section)


class CardCompositionTests(unittest.TestCase):
    """C4/C5: card anatomy, thumbnails, and humanized status chips (U15)."""

    def test_board_card_uses_the_thumbnail_component(self):
        jobs = source(JOBS_VIEW)
        self.assertIn("<Thumbnail", jobs)
        self.assertGreaterEqual(jobs.count("<Thumbnail"), 2)  # board + archive rows
        self.assertNotIn("card-thumb", jobs)
        self.assertNotIn("archive-thumb", jobs)

    def test_thumbnail_component_serves_the_phase1_endpoint(self):
        api = source(API_JS)
        self.assertIn("thumbnailUrl", api)
        self.assertIn("/sources/", api)
        self.assertIn("/thumbnail", api)
        thumbnail = source(THUMBNAIL)
        # The generic video icon is the load/error fallback only.
        self.assertIn("state !== 'loaded'", thumbnail)
        self.assertIn("onerror", thumbnail)

    def test_quick_actions_are_icon_buttons_with_names_and_tooltips(self):
        jobs = source(JOBS_VIEW)
        for action in ("play", "calendarX", "trash"):
            self.assertIn(f'name="{action}"', jobs)
        icon_buttons = jobs.count('class="btn btn-ghost btn-icon"')
        # Every quick action carries both a tooltip and an accessible name.
        self.assertGreaterEqual(jobs.count("title="), icon_buttons)
        self.assertGreaterEqual(jobs.count("aria-label="), icon_buttons)

    def test_status_chips_are_humanized_never_raw_keys(self):
        jobs = source(JOBS_VIEW)
        self.assertIn("{humanize(job.status)}", jobs)
        self.assertIn("{humanize(job.current_checkpoint)}", jobs)
        # No raw enum key reaches a card chip.
        self.assertNotIn("{job.status}", jobs)

    def test_calendarX_icon_exists_for_the_cancel_attempt_action(self):
        self.assertIn("calendarX", source(ICON))


if __name__ == "__main__":
    unittest.main()
